"""###Petición a la web"""

headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'}
response = requests.get('https://www.transfermarkt.es/espana/startseite/verein/3375', headers=headers)
soup = BeautifulSoup(response.text, 'html.parser')

"""### Scraping y creacion Data Frame con Pandas"""

tabla = soup.find(class_='responsive-table')
filas = tabla.find('tbody').find_all('tr')

lista_jugadores = []

for fila in filas:
    tds = fila.find_all('td', recursive=False)
    if len(tds) < 5:
        continue

    posicion = tds[0].get('title')
    if not posicion:
        continue

    td_hauptlink = tds[1].find('td', class_='hauptlink')
    nombre_tag = td_hauptlink.find('a') if td_hauptlink else None
    nombre = nombre_tag.get_text().strip()

    edad = tds[2].get_text().strip()

    club_tag = tds[3].find('a')
    club = club_tag['title']

    valor_tag = tds[4].find('a')
    valor = valor_tag.get_text().strip()

    jugador = {
        'Nombre': nombre,
        'Posicion': posicion,
        'Edad': edad,
        'Club': club,
        'Valor': valor
    }

    lista_jugadores.append(jugador)

df = pd.DataFrame(lista_jugadores)

#Limpiar los datos para poder usar los valores numéricos de edad y valor
df['Edad'] = df['Edad'].str.split('(').str[1].str.replace(')', '').astype(int)

df['Valor'] = df['Valor'].str.replace(' €', '').str.replace(',', '.')

df['Valor'] = df['Valor'].apply(lambda x: float(x.replace(' mill.', ''))) #Elimina el texto " mill." y convierte la cifra a número decimal (float)
##lambda: función rápida de una sola línea que transforma cada celda (x)

