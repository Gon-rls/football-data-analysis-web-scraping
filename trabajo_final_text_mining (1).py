"""###Gráfico de Pesos"""

#Prepara los datos
conteo_clubes = df['Club'].value_counts()
max_jugadores = conteo_clubes.max()

#Preparar el gráfico
G = nx.Graph()
centro = 'España'
G.add_node(centro, tipo='Centro')

#Diccionario para guardar las coordenadas X, Y exactas de cada elemento
posiciones = {centro: np.array([0.0, 0.0])} # España en el centro exacto

#Distincia y la 'orbita' con el centro
num_clubes = len(conteo_clubes)
angulos = np.linspace(0, 2 * np.pi, num_clubes, endpoint=False)

for i, (club, cantidad) in enumerate(conteo_clubes.items()):
    G.add_node(club, tipo='Club', jugadores=cantidad)
    G.add_edge(centro, club, weight=cantidad)
    radio = 1 + (max_jugadores - cantidad) * 0.8

    x = radio * np.cos(angulos[i])
    y = radio * np.sin(angulos[i])
    posiciones[club] = np.array([x, y])

plt.figure(figsize=(12, 10))

#Sacar los nodos
nodos_centro = [n for n, attr in G.nodes(data=True) if attr.get('tipo') == 'Centro']
nodos_club = [n for n, attr in G.nodes(data=True) if attr.get('tipo') == 'Club']

#Hacer que el tamaño de la burbuja del club también crezca según sus jugadores
tamaños_club = [G.nodes[n]['jugadores'] * 800 for n in nodos_club]

#Dibujar las líneas de conexión (más gruesas = más jugadores)
pesos_aristas = [G[u][v]['weight'] for u, v in G.edges()]
nx.draw_networkx_edges(G, posiciones, width=pesos_aristas, alpha=0.4, edge_color='gray')

#Nodos
nx.draw_networkx_nodes(G, posiciones, nodelist=nodos_centro, node_color='#C44E52', node_size=4000, edgecolors='black')
nx.draw_networkx_nodes(G, posiciones, nodelist=nodos_club, node_color='#4C72B0', node_size=tamaños_club, edgecolors='black')

#Textos
nx.draw_networkx_labels(G, posiciones, font_size=10, font_weight='bold')

plt.title('Mapa de Influencia: Peso de los Clubes en la Selección', fontsize=16, fontweight='bold')
plt.tight_layout()
plt.show()

